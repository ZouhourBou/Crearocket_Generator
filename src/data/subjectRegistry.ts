/**
 * SUBJECT_REGISTRY — Central Registry for all 26 School Notebook Subjects
 * 
 * Strict Architecture Rules:
 * 1. 26 Subjects × 12 Templates = 312 Subject/Template Combinations.
 * 2. Hard Subject Lock: att_2 is the sole source of truth.
 * 3. AI artwork is strictly visual with NO readable text (anti-hallucination).
 * 4. Programmatic rendering of att_3 (main title) in template.titleZone.
 * 5. Programmatic rendering of att_4..att_7 in template.infoZone.
 */

import { NotebookPageFormat } from '../types';

export type SubjectLanguage = 'ar' | 'fr' | 'en' | 'mixed';
export type TextDirection = 'rtl' | 'ltr';

export interface LayoutZone {
  x: number; // percentage from left (0 to 100)
  y: number; // percentage from top (0 to 100)
  width: number; // percentage width (0 to 100)
  height: number; // percentage height (0 to 100)
}

export interface TitleZone extends LayoutZone {
  textAlign: 'center' | 'right' | 'left';
  verticalAlign: 'top' | 'middle' | 'bottom';
  fontFamily: string;
  fontWeight: string;
  minFontSize: number;
  maxFontSize: number;
  lineHeight: number;
  textEffects: {
    color: string;
    backgroundPlate: boolean;
    plateColor?: string;
    plateBorder?: string;
    plateShadow?: string;
    shadow?: string;
  };
}

export interface InfoZone extends LayoutZone {
  styleVariant: 'card' | 'badge' | 'minimal' | 'glass' | 'framed';
  backgroundColor: string;
  borderColor: string;
  textColor: string;
  accentColor: string;
  borderRadius: number;
  padding: number;
}

export type ArtDirectionId =
  | 'premium_school'
  | 'cute_school'
  | 'paper_craft'
  | 'doodle_academy'
