/**
 * Pre-render Layout Validation
 * Enforces all 6 checks before presenting the cover to the user
 */
export interface LayoutValidationResult {
  valid: boolean;
  errors: string[];
  warnings: string[];
}

export function validateCoverLayout(
  subjectId: string,
  template: CoverTemplate,
  titleText: string,
  studentInfo: {
    fullName?: string;
    grade?: string;
    schoolName?: string;
    academicYear?: string;
  }
): LayoutValidationResult {
  const errors: string[] = [];
  const warnings: string[] = [];

  // 1. Subject Consistency
  if (!subjectId) {
    errors.push('Missing subject ID');
  } else if (template.subjectId !== subjectId) {
    errors.push(`Template mismatch: template belongs to ${template.subjectId}, requested ${subjectId}`);
  }

  // 2. Title validation
  if (!titleText || !titleText.trim()) {
    errors.push('Title (att_3) cannot be empty');
  }

  // 3. Information Panel validation
  if (!template.infoZone || template.infoZone.height <= 0) {
    errors.push('Invalid infoZone geometry');
  }

  // 4. Safe Zone check
  if (template.titleZone.y < 4 || template.titleZone.y + template.titleZone.height > 96) {
    warnings.push('Title zone extends into edge bleed margin');
  }

  return {
    valid: errors.length === 0,
    errors,
    warnings,
  };
}

