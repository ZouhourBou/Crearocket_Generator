/**
 * Resolves a subject ID or label to the exact registered subject ID
 */
export function resolveSubjectId(rawInput: string): string {
  if (!rawInput) return 'autre';
  const normalized = rawInput.trim().toLowerCase();

  // Exact ID match
  if (SUBJECT_REGISTRY[normalized]) return normalized;

  // Alias match
  if (SUBJECT_ALIASES[normalized]) return SUBJECT_ALIASES[normalized];

  // Match by exact label
  const foundByLabel = RAW_SUBJECTS.find((s) => s.label === rawInput.trim());
  if (foundByLabel) return foundByLabel.id;

  // Partial match fallback
  const foundPartial = RAW_SUBJECTS.find((s) =>
    rawInput.includes(s.label) || s.label.includes(rawInput)
  );
  if (foundPartial) return foundPartial.id;

  return 'autre';
}

/**
 * Retrieves the SubjectDefinition with strict verification
 */
export function getSubjectDefinition(subjectId: string): SubjectDefinition {
  const resolvedId = resolveSubjectId(subjectId);
  const subject = SUBJECT_REGISTRY[resolvedId];
  if (!subject) {
    return SUBJECT_REGISTRY.autre;
  }
  return subject;
}

/**
 * Anti-repetition state memory per subject
 */
export const lastTemplateBySubject: Record<string, number> = {};

/**
 * Selects an artistic model for a subject, respecting the active 5-model pool (or user requested model)
 * strictly avoiding repeating the immediately previous model to guarantee variety.
 */
export function selectNextTemplateForSubject(
  subjectId: string,
  preferredTemplateId?: number
): CoverTemplate {
  const subject = getSubjectDefinition(subjectId);
  const activePool = subject.templates.slice(0, ACTIVE_MODEL_COUNT);

  // If specific template requested and valid
  if (preferredTemplateId && preferredTemplateId >= 1 && preferredTemplateId <= subject.templates.length) {
    const directMatch = subject.templates.find((t) => t.id === preferredTemplateId);
    if (directMatch) {
      lastTemplateBySubject[subject.id] = directMatch.id;
      return directMatch;
    }
  }

  const lastId = lastTemplateBySubject[subject.id];
  const candidates = activePool.filter((t) => t.id !== lastId);

  // Fallback to active pool if candidates is empty
  const pool = candidates.length > 0 ? candidates : activePool;
  const chosen = pool[Math.floor(Math.random() * pool.length)] || activePool[0];

  lastTemplateBySubject[subject.id] = chosen.id;
  return chosen;
}

