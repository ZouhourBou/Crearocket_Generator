/**
 * Generates 12 distinct templates for a given subject definition
 */
function buildSubjectTemplates(
  subjectId: string,
  subjectLabel: string,
  direction: TextDirection,
  palette: string[],
  allowedObjects: string[],
  forbiddenObjects: string[]
): CoverTemplate[] {
  const primaryColor = palette[0] || '#2563EB';
  const secondaryColor = palette[1] || '#0D9488';
  const bgColor = palette[2] || '#F8FAFC';
  const accentColor = palette[3] || '#F59E0B';

  const primarySubset = allowedObjects.slice(0, 4);
  const secondarySubset = allowedObjects.slice(4);

  return ART_DIRECTIONS.map((arch) => {
    const titleZone: TitleZone & {
      styleVariant: '3d_premium' | 'cute_playful' | 'paper_cut' | 'doodle_sketch' | 'luxury_editorial';
    } = {
      x: arch.titleX,
      y: arch.titleY,
      width: arch.titleW,
      height: arch.titleH,
      textAlign: 'center',
      verticalAlign: 'middle',
      fontFamily: direction === 'rtl' ? 'Cairo, Tajawal, sans-serif' : 'Outfit, Plus Jakarta Sans, sans-serif',
      fontWeight: '800',
      minFontSize: 16,
      maxFontSize: 34,
      lineHeight: 1.25,
      styleVariant: arch.titleStyleVariant,
      textEffects: {
        color: arch.plate ? '#FFFFFF' : primaryColor,
        backgroundPlate: arch.plate,
        plateColor: arch.plate ? primaryColor : 'transparent',
        plateBorder: arch.plate ? `${secondaryColor}80` : 'transparent',
        plateShadow: arch.plate ? '0 10px 25px -5px rgba(0,0,0,0.18)' : 'none',
        shadow: arch.plate ? '0 2px 4px rgba(0,0,0,0.3)' : '0 2px 8px rgba(255,255,255,0.9)',
      },
    };

    const infoZone: InfoZone & {
      customCardStyle: 'premium_3d' | 'cute_kawaii' | 'paper_relief' | 'doodle_sheet' | 'luxury_filigree';
    } = {
      x: arch.infoX,
      y: arch.infoY,
      width: arch.infoW,
      height: arch.infoH,
      styleVariant: arch.infoStyleVariant,
      customCardStyle: arch.infoCustomCardStyle,
      backgroundColor: arch.artDirection === 'luxury_education' ? 'rgba(252, 251, 247, 0.98)' : 'rgba(255, 255, 255, 0.98)',
      borderColor: `${secondaryColor}70`,
      textColor: '#0F172A',
      accentColor: primaryColor,
      borderRadius: arch.infoBorderRadius,
      padding: 14,
    };

    const decorativeZones: LayoutZone[] = [
      { x: 0, y: arch.titleY + arch.titleH, width: 100, height: arch.infoY - (arch.titleY + arch.titleH) },
      { x: 0, y: 0, width: 100, height: 100 },
    ];

    const forbiddenZones: LayoutZone[] = [
      titleZone,
      infoZone,
    ];

    const illustrationPrompt = [
      MINIMAL_QUALITY_PROMPT,
      `Modèle artistique sélectionné : ${arch.name} (${arch.artDirection}).`,
      `Style visuel : ${arch.illustrationStyle}.`,
      `Style d'arrière-plan : ${arch.backgroundStyle}.`,
      `Style de bordure : ${arch.borderStyle}.`,
      `Règles de composition : ${arch.compositionRules}.`,
      `Matière exclusive (att_2) : ${subjectLabel} (${subjectId}).`,
      `Objets principaux autorisés UNIQUEMENT : ${primarySubset.join(', ')}.`,
      secondarySubset.length > 0 ? `Objets secondaires autorisés : ${secondarySubset.join(', ')}.` : '',
      `Palette chromatique officielle : ${palette.join(', ')}.`,
      `Zone réservée pour le titre : haut du cahier (y: ${arch.titleY}% à ${arch.titleY + arch.titleH}%). Laisser propre et non obstrué.`,
      `Zone réservée pour le cartouche élève : bas du cahier (y: ${arch.infoY}% à ${arch.infoY + arch.infoH}%). Laisser propre et net.`,
      `AUCUN mot, AUCUN texte, AUCUNE lettre dans l'illustration d'arrière-plan.`,
    ].filter(Boolean).join(' ');

    const negativePrompt = [
      GLOBAL_NEGATIVE_PROMPT,
      ...forbiddenObjects,
    ].join(', ');

    return {
      id: arch.id,
      subjectId,
      name: arch.name,
      artDirection: arch.artDirection,
      artDirectionName: arch.artDirectionName,
      palette,
      illustrationStyle: arch.illustrationStyle,
      primaryObjects: primarySubset,
      secondaryObjects: secondarySubset,
      backgroundStyle: arch.backgroundStyle,
      borderStyle: arch.borderStyle,
      composition: arch.composition,
      compositionRules: arch.compositionRules,
      titleZone,
      infoZone,
      decorativeZones,
      forbiddenZones,
      imagePrompt: illustrationPrompt,
      illustrationPrompt,
      negativePrompt,
    };
  });
}

